import json
from pathlib import Path
from rich.console import Console

console = Console()

def generate_frida_script(report_dir: Path):
    report_file = report_dir / "initial_intel.json"
    if not report_file.exists():
        return
        
    with open(report_file, 'r', encoding='utf-8') as f:
        intel = json.load(f)
        
    findings = intel.get("static_analysis_findings", {})
    root_files = findings.get("root_detection", [])
    
    if not root_files:
        console.print("[yellow][*] No root detection found. Skipping Frida generation.[/yellow]")
        return
        
    console.print("[*] Generating advanced Frida bypass script...")
    
    # Собираем ВСЕ уникальные классы, связанные с root detection
    classes_to_hook = set()
    for item in root_files:
        class_name = item["file"].replace("sources/", "").replace(".java", "").replace("/", ".")
        classes_to_hook.add(class_name)
        
    frida_code = "/*\n * Auto-generated by re-mobile-auto\n * Target: Root Detection Bypass\n */\nJava.perform(function() {\n"
    
    for cls in classes_to_hook:
        frida_code += f'''    console.log("[*] Hooking: {cls}");
    try {{
        var TargetClass = Java.use("{cls}");
        var methods = TargetClass.class.getDeclaredMethods();
        for (var i = 0; i < methods.length; i++) {{
            if (methods[i].getReturnType().getName() === 'boolean') {{
                console.log("  [+] Hooking boolean method: " + methods[i].getName());
                TargetClass[methods[i].getName()].implementation = function() {{
                    console.log("  [+] Bypassed! Returning false.");
                    return false;
                }};
            }}
        }}
    }} catch (e) {{
        console.log("  [-] Hook failed: " + e);
    }}
'''
    frida_code += "});\n"
        
    output_file = report_dir / "frida_bypass.js"
    with open(output_file, "w", encoding="utf-8") as f_out:
        f_out.write(frida_code)
        
    console.print(f"[green][+][/green] Advanced Frida script saved to: [bold]{output_file}[/bold]")
    console.print(f"[cyan][i][/cyan] Will attempt to hook {len(classes_to_hook)} unique classes.")
